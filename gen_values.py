#!/usr/bin/env python3
# Regenerates colors.yp (from raylib.h's Color #defines, which bindgen can't see)
# and constants.yp (every bind enum variant in binds.yp, as a plain i32).
import re

header = open("raylib.h").read()
colors = ["// raylib.h's colors are #define macros, which bindgen can't see. Generated by gen_values.py.", ""]
for name, vals in re.findall(r'^#define ([A-Z]+)\s+CLITERAL\(Color\)\{\s*([0-9, ]+?)\s*\}', header, re.M):
    colors.append(f"Color {name} = {{{', '.join(v.strip() for v in vals.split(','))}}};")
open("colors.yp", "w").write("\n".join(colors) + "\n")

binds = open("binds.yp").read()
# raylib takes these flag sets as unsigned int (SetConfigFlags, SetWindowState, SetGesturesEnabled, ...).
UNSIGNED = {"ConfigFlags", "Gesture"}
consts = ["// raylib's enum values as plain integer constants, since raylib's functions take ints, not the enum.",
          "// Generated from binds.yp by gen_values.py.", ""]
for enum, body in re.findall(r'^bind enum (\w+) \{\n(.*?)^\}', binds, re.S | re.M):
    names = re.findall(r'^\s+(\w+) = ', body, re.M)
    if not names:
        continue
    consts.append(f"// {enum}")
    t = "u32" if enum in UNSIGNED else "i32"
    consts += [f"{t} {v} = {enum}.{v}.({t});" for v in names]
    consts.append("")
open("constants.yp", "w").write("\n".join(consts))
